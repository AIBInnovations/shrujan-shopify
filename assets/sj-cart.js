/* ==========================================================================
   The bag drawer (snippets/sj-cart-drawer.liquid, styles in sj-cart.css).
   Hand-written, not generated by export_theme.

   Everything goes through Shopify's cart API (/cart.js, /cart/add.js,
   /cart/change.js, /cart/update.js) one request at a time, and every total
   drawn is the one the cart sends back, so discounts and prices are always
   Shopify's own.

   What opens it:
     - a card's "Add to bag" label (.piece__quick with data-variant): adds the
       piece at once, in its first size that can be bought; a piece with
       sizes or colours gets a dropdown on its line in the bag to change it;
     - any form posting to /cart/add (the product page): sent in the
       background instead of leaving the page;
     - any link to the cart, and #cart in the address (the cart page sends
       the shopper back with it).
   "Add to bag" always stays "Add to bag" (the user, 2026-10-29): it adds and
   opens the drawer, and Checkout lives in the drawer only, carrying the
   tier's discount code when one is set.
   window.SJCart = { open, close, add, refresh } for anything else.
   ========================================================================== */
(() => {
  const root = document.getElementById('sj-cart');
  const dataEl = document.getElementById('sj-cart-data');
  if (!root || !dataEl) return;
  let D;
  try { D = JSON.parse(dataEl.textContent); } catch (e) { return; }

  const doc = document;
  const R = D.routes;
  const slash = (p) => (p.endsWith('/') ? p : p + '/');
  const cartPath = new URL(R.cart, location.origin).pathname.replace(/\/$/, '');
  const reduced = matchMedia('(prefers-reduced-motion: reduce)').matches;
  const touch = matchMedia('(hover: none)').matches;
  const q = (s, el = root) => el.querySelector(s);

  const panel = q('.sjc__panel');
  const body = q('[data-sjc-body]');
  const linesEl = q('[data-sjc-lines]');
  const emptyEl = q('[data-sjc-empty]');
  const foot = q('[data-sjc-foot]');
  const sumsEl = q('[data-sjc-sums]');
  const countEl = q('[data-sjc-count]');
  const noticeEl = q('[data-sjc-notice]');
  const tiersEl = q('[data-sjc-tiers]');
  const tierMsg = q('[data-sjc-tier-msg]');
  const track = q('[data-sjc-track]');
  const fill = q('[data-sjc-fill]');
  const recsEl = q('[data-sjc-recs]');
  const rail = q('[data-sjc-rail-list]');
  const noteEl = q('[data-sjc-note]');

  let cart = D.cart && D.cart.items ? D.cart : null;
  let isOpen = false;
  let lastFocus = null;

  /* ---- money, text, pictures ------------------------------------------- */
  const decode = (s) => { const t = doc.createElement('textarea'); t.innerHTML = s; return t.value; };
  const FORMAT = decode(String(D.money || '₹{{amount}}').replace(/<[^>]*>/g, ''));
  const group = (cents, dec, th, ds) => {
    const [i, f] = (cents / 100).toFixed(dec).split('.');
    return i.replace(/\B(?=(\d{3})+(?!\d))/g, th) + (f ? ds + f : '');
  };
  const money = (cents) => {
    const c = Math.round(Number(cents) || 0);
    return FORMAT.replace(/\{\{\s*(\w+)\s*\}\}/, (m, k) => {
      switch (k) {
        case 'amount_no_decimals': return group(c, 0, ',', '.');
        case 'amount_with_comma_separator': return group(c, 2, '.', ',');
        case 'amount_no_decimals_with_comma_separator': return group(c, 0, '.', ',');
        case 'amount_with_apostrophe_separator': return group(c, 2, "'", '.');
        case 'amount_with_space_separator': return group(c, 2, ' ', ',');
        case 'amount_no_decimals_with_space_separator': return group(c, 0, ' ', ',');
        default: return group(c, 2, ',', '.');
      }
    });
  };
  const esc = (s) => String(s == null ? '' : s).replace(/[&<>"']/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[ch]));
  const pic = (url, w) => {
    if (!url) return '';
    try {
      const u = new URL(String(url).replace(/^\/\//, 'https://'), location.origin);
      u.searchParams.set('width', w);
      return u.toString();
    } catch (e) { return url; }
  };
  const icon = (name) => `<i class="sj-i sj-i--${name} ms" aria-hidden="true"></i>`;
  // the shop's own currency rate, so the tiers (set in rupees) hold in any
  // currency the shopper sees the store in
  const rate = () => parseFloat((window.Shopify && Shopify.currency && Shopify.currency.rate) || 1) || 1;

  /* ---- the cart API, one request at a time ------------------------------ */
  let chain = Promise.resolve();
  const queue = (fn) => {
    const p = chain.then(fn);
    chain = p.catch(() => {});
    return p;
  };
  const call = (url, opts) => fetch(url, Object.assign({ credentials: 'same-origin', headers: { Accept: 'application/json' } }, opts))
    .then((r) => r.json().catch(() => ({})).then((j) => {
      if (!r.ok) {
        const err = new Error(j.description || j.message || 'Something went wrong. Please try again.');
        err.status = r.status;
        throw err;
      }
      return j;
    }));
  const post = (url, data) => call(url, {
    method: 'POST',
    headers: { Accept: 'application/json', 'Content-Type': 'application/json' },
    body: JSON.stringify(data)
  });
  const getCart = () => call(R.cart + '.js?t=' + Date.now());

  const emit = () => doc.dispatchEvent(new CustomEvent('sj:cart', { detail: cart }));

  // every new cart from Shopify goes through here
  function took(c) {
    cart = c;
    render();
    loadRecs();
    emit();
    syncCode(c);
  }

  function refresh() {
    return queue(getCart).then((c) => { took(c); return c; });
  }

  // adds lines, then reads the whole cart back; resolves to the added keys
  function add(items) {
    return queue(() => post(R.add + '.js', { items })
      .then((res) => getCart().then((c) => { cart = c; return (res.items || [res]).map((i) => i.key); })))
      .then((keys) => { took(cart); return keys; });
  }

  function addForm(fd) {
    return queue(() => call(R.add + '.js', { method: 'POST', body: fd, headers: { Accept: 'application/json', 'X-Requested-With': 'XMLHttpRequest' } })
      .then((res) => getCart().then((c) => { cart = c; return (res.items || [res]).map((i) => i.key); })))
      .then((keys) => { took(cart); return keys; });
  }

  /* ---- open and close --------------------------------------------------- */
  const hold = (on) => {
    const S = window.Shrujan;
    if (S && (on ? S.stopScroll : S.startScroll)) (on ? S.stopScroll : S.startScroll)();
    doc.documentElement.style.overflow = on ? 'hidden' : '';
    doc.documentElement.classList.toggle('sjc-open', on);
  };

  let hideTimer = 0;
  // fresh: the cart was just read (after an add), so it is not read again
  function open(fresh) {
    clearTimeout(hideTimer);
    if (isOpen) return;
    isOpen = true;
    lastFocus = doc.activeElement;
    fill.style.width = '0%';
    root.hidden = false;
    hold(true);
    requestAnimationFrame(() => requestAnimationFrame(() => {
      root.classList.add('is-open');
      render();
      railArrows();
    }));
    if (!touch) setTimeout(() => { const c = q('.sjc__close'); if (c) c.focus({ preventScroll: true }); }, 60);
    if (fresh !== true) refresh().catch(() => {});
  }

  function close() {
    if (!isOpen) return;
    isOpen = false;
    root.classList.remove('is-open');
    hold(false);
    hideTimer = setTimeout(() => { root.hidden = true; notice(''); }, reduced ? 0 : 560);
    if (lastFocus && lastFocus.focus) lastFocus.focus({ preventScroll: true });
  }

  root.addEventListener('click', (e) => { if (e.target.closest('[data-sjc-close]')) { e.preventDefault(); close(); } });

  doc.addEventListener('keydown', (e) => {
    if (!isOpen) return;
    if (e.key === 'Escape') {
      e.preventDefault();
      close();
      return;
    }
    if (e.key !== 'Tab') return;
    // keep the keyboard inside the drawer while it is open
    const all = [].filter.call(panel.querySelectorAll('a[href], button:not([disabled]), textarea, input, select, summary, [tabindex]:not([tabindex="-1"])'), (el) => el.offsetParent !== null);
    if (!all.length) return;
    const first = all[0];
    const last = all[all.length - 1];
    if (e.shiftKey && (doc.activeElement === first || !panel.contains(doc.activeElement))) { e.preventDefault(); last.focus(); }
    else if (!e.shiftKey && doc.activeElement === last) { e.preventDefault(); first.focus(); }
  });

  // a swipe to the right closes it on phones (not on the sideways rail)
  let sx = 0, sy = 0, swiping = false;
  panel.addEventListener('touchstart', (e) => {
    const t = e.touches[0];
    swiping = !e.target.closest('.sjc__rail, select, textarea');
    sx = t.clientX; sy = t.clientY;
  }, { passive: true });
  panel.addEventListener('touchend', (e) => {
    if (!swiping) return;
    const t = e.changedTouches[0];
    const dx = t.clientX - sx, dy = t.clientY - sy;
    if (dx > 90 && Math.abs(dy) < dx * 0.5) close();
  }, { passive: true });

  /* ---- messages --------------------------------------------------------- */
  let noticeTimer = 0;
  // errors show on the drawer; good news is already drawn (the line lights up,
  // the bar fills), so it is only read out to screen readers
  function notice(text, kind) {
    clearTimeout(noticeTimer);
    noticeEl.textContent = text || '';
    noticeEl.hidden = !text;
    noticeEl.className = 'sjc__notice' + (kind ? ' sjc__notice--' + kind : '');
    if (text) noticeTimer = setTimeout(() => notice(''), kind === 'error' ? 6000 : 3200);
  }

  function added() {
    notice(unlocked ? 'Added. You have unlocked ' + unlocked + '.' : 'Added to your bag.', 'good');
    unlocked = '';
  }

  /* ---- the header's Bag (n) --------------------------------------------- */
  let shownCount = cart ? cart.item_count : null;
  function badges(n) {
    const bump = shownCount !== null && n !== shownCount;
    shownCount = n;
    doc.querySelectorAll('[data-sj-bag]').forEach((a) => {
      a.setAttribute('aria-label', 'Shopping bag, ' + n + (n === 1 ? ' item' : ' items'));
      const t = a.querySelector('[data-sj-bag-text]');
      if (t) t.innerHTML = 'Bag&nbsp;(' + n + ')';
      let b = a.querySelector('.utility-count');
      if (n > 0) {
        if (!b) {
          b = doc.createElement('b');
          b.className = 'utility-count';
          b.setAttribute('aria-hidden', 'true');
          a.insertBefore(b, a.querySelector('.sj-i'));
        }
        b.textContent = n;
        if (bump) { b.classList.remove('is-bump'); void b.offsetWidth; b.classList.add('is-bump'); }
      } else if (b) b.remove();
    });
  }

  /* ---- the tier bar ----------------------------------------------------- *
     Each tier sits in the middle of an equal step of the bar, its amount and
     reward under it; the fill runs between them by how far the bag has got. */
  const tierList = () => (D.tiers || [])
    .map((t) => ({ at: Math.round(t.at * rate()), label: t.label, code: String(t.code || '').trim() }))
    .filter((t) => t.at > 0)
    .sort((a, b) => a.at - b.at);

  let marks = [];
  let reachedBefore = null; // null until the bar is first drawn
  let unlocked = '';
  function buildTrack(tiers) {
    if (marks.length === tiers.length) return;
    [].forEach.call(track.querySelectorAll('.sjc__mark'), (m) => m.remove());
    marks = tiers.map((t, i) => {
      const m = doc.createElement('span');
      m.className = 'sjc__mark';
      m.style.left = ((i + 0.5) / tiers.length) * 100 + '%';
      m.innerHTML = `<i class="sjc__dia" aria-hidden="true"></i><span class="sjc__mark-txt"><b>${esc(money(t.at))}</b><small>${esc(t.label)}</small></span>`;
      track.appendChild(m);
      return m;
    });
  }

  const reachedOf = (tiers, v) => { let r = -1; tiers.forEach((t, i) => { if (v >= t.at) r = i; }); return r; };

  function renderTiers(c) {
    unlocked = ''; // set again below only when this very change reaches a tier
    const tiers = tierList();
    if (!D.tiersOn || !tiers.length || !c.item_count) { tiersEl.hidden = true; if (cart) reachedBefore = -1; return; }
    tiersEl.hidden = false;
    buildTrack(tiers);
    // the minimum purchase Shopify checks is the bag before order discounts
    const v = c.items_subtotal_price;
    const n = tiers.length;
    const pos = (i) => (i + 0.5) / n;
    const reached = reachedOf(tiers, v);
    let f = 1;
    if (reached < n - 1) {
      const from = reached < 0 ? 0 : tiers[reached].at;
      const to = tiers[reached + 1].at;
      const p0 = reached < 0 ? 0 : pos(reached);
      f = p0 + (pos(reached + 1) - p0) * Math.max(0, Math.min(1, (v - from) / (to - from)));
    }
    fill.style.width = (f * 100).toFixed(2) + '%';
    marks.forEach((m, i) => {
      m.classList.toggle('is-on', i <= reached);
      m.classList.toggle('is-next', i === reached + 1);
    });
    const next = tiers[reached + 1];
    const withCode = (t) => (t.code ? ` with code <b>${esc(t.code)}</b>` : '');
    if (next) {
      tierMsg.innerHTML = `Add <b>${esc(money(next.at - v))}</b> more to unlock <b>${esc(next.label)}</b>${withCode(next)}`;
    } else {
      const top = tiers[n - 1];
      tierMsg.innerHTML = `${icon('check-circle')} You have unlocked <b>${esc(top.label)}</b>${top.code ? `, code <b>${esc(top.code)}</b> applied` : ''}`;
    }
    if (reachedBefore !== null && reached > reachedBefore && marks[reached]) {
      const m = marks[reached];
      m.classList.remove('is-pop'); void m.offsetWidth; m.classList.add('is-pop');
      unlocked = tiers[reached].label;
      notice('You have unlocked ' + unlocked + '.', 'good');
    }
    reachedBefore = reached;
  }

  /* ---- discount codes on tiers ----------------------------------------- *
     The code of the highest tier reached is put on the cart (Shopify shows
     its discount in the totals) and on the way to checkout. Only a code the
     bag put on is ever taken off again; each change is tried once. */
  let ourCode = '';
  try { ourCode = sessionStorage.getItem('sjc-code') || ''; } catch (e) {}
  let codeTried = null;
  const wantedCode = (c) => {
    const tiers = tierList();
    if (!D.tiersOn || !c || !c.item_count) return '';
    let code = '';
    tiers.forEach((t) => { if (c.items_subtotal_price >= t.at && t.code) code = t.code; });
    return code;
  };
  function syncCode(c) {
    const want = wantedCode(c);
    const have = (c.discount_codes || []).map((d) => d.code).filter(Boolean);
    const lc = (x) => String(x).toLowerCase();
    const mine = ourCode && have.some((x) => lc(x) === lc(ourCode)) && lc(ourCode) !== lc(want);
    const missing = want && !have.some((x) => lc(x) === lc(want));
    if (!mine && !missing) { ourCode = want; return; }
    const next = have.filter((x) => !ourCode || lc(x) !== lc(ourCode)).concat(want ? [want] : []).join(',');
    if (codeTried === next) return;
    codeTried = next;
    ourCode = want;
    try { sessionStorage.setItem('sjc-code', ourCode); } catch (e) {}
    queue(() => post(R.update + '.js', { discount: next }))
      .then((nc) => { if (nc && nc.items) { cart = nc; render(); emit(); } })
      .catch(() => {});
  }
  const checkoutUrl = () => {
    const code = wantedCode(cart);
    return slash(R.root) + 'checkout' + (code ? '?discount=' + encodeURIComponent(code) : '');
  };

  /* ---- the lines -------------------------------------------------------- */
  function lineHTML(it) {
    const img = it.image ? `<img src="${esc(pic(it.image, 300))}" alt="${esc(it.featured_image && it.featured_image.alt || it.product_title)}" loading="lazy" width="150" height="188">` : '';
    const opts = picksHTML(it) || (it.options_with_values || [])
      .filter((o) => o && o.value && !/^default title$/i.test(o.value) && !/^title$/i.test(o.name))
      .map((o) => `<p class="sjc-line__opt">${esc(o.name)}: ${esc(o.value)}</p>`).join('')
      || (it.variant_title && !/^default title$/i.test(it.variant_title) ? `<p class="sjc-line__opt">${esc(it.variant_title)}</p>` : '');
    const props = it.properties ? Object.keys(it.properties)
      .filter((k) => k.charAt(0) !== '_' && it.properties[k] !== '' && it.properties[k] != null)
      .map((k) => `<p class="sjc-line__opt">${esc(k)}: ${esc(it.properties[k])}</p>`).join('') : '';
    const discs = (it.line_level_discount_allocations || [])
      .filter((d) => d.amount > 0)
      .map((d) => `<p class="sjc-line__disc">${icon('tag')} ${esc(d.discount_application && d.discount_application.title || 'Discount')} (−${esc(money(d.amount))})</p>`).join('');
    const was = it.original_line_price > it.final_line_price ? `<s>${esc(money(it.original_line_price))}</s>` : '';
    const each = it.quantity > 1 ? `<small>${esc(money(it.final_price))} each</small>` : '';
    return `<li class="sjc-line" data-key="${esc(it.key)}">
      <a class="sjc-line__media" href="${esc(it.url)}" tabindex="-1" aria-hidden="true">${img}</a>
      <div class="sjc-line__info">
        <a class="sjc-line__name" href="${esc(it.url)}">${esc(it.product_title)}</a>
        <p class="sjc-line__price">${was}<span>${esc(money(it.final_line_price))}</span>${each}</p>
        ${opts}${props}${discs}
        <p class="sjc-line__err" data-err hidden></p>
      </div>
      <div class="sjc-qty" role="group" aria-label="Quantity of ${esc(it.product_title)}">
        <button type="button" class="sjc-qty__btn" data-act="dec" aria-label="${it.quantity > 1 ? 'One fewer' : 'Remove'}">${icon('minus')}</button>
        <span class="sjc-qty__n" aria-live="polite">${it.quantity}</span>
        <button type="button" class="sjc-qty__btn" data-act="inc" aria-label="One more">${icon('plus')}</button>
      </div>
      <button type="button" class="sjc-line__remove" data-act="remove">Remove item</button>
    </li>`;
  }

  function renderSums(c) {
    const rows = [];
    const orderDiscs = (c.cart_level_discount_applications || []).filter((d) => d.total_allocated_amount > 0);
    rows.push(`<div class="sjc__sum"><dt>Subtotal</dt><dd>${esc(money(c.items_subtotal_price))}</dd></div>`);
    orderDiscs.forEach((d) => {
      rows.push(`<div class="sjc__sum sjc__sum--disc"><dt>${icon('tag')} ${esc(d.title || 'Discount')}</dt><dd>−${esc(money(d.total_allocated_amount))}</dd></div>`);
    });
    // a tier whose reward is free shipping, once reached, says so here
    const tiers = tierList();
    const r = reachedOf(tiers, c.items_subtotal_price);
    const freeShip = D.tiersOn && tiers.some((t, i) => i <= r && /free\s*shipping/i.test(t.label));
    rows.push(`<div class="sjc__sum sjc__sum--ship"><dt>Shipping</dt><dd>${esc(freeShip ? 'Free' : (D.shipValue || 'Calculated at checkout'))}</dd></div>`);
    if (orderDiscs.length || c.original_total_price > c.total_price) {
      rows.push(`<div class="sjc__sum sjc__sum--total"><dt>Total</dt><dd>${esc(money(c.total_price))}</dd></div>`);
    }
    sumsEl.innerHTML = rows.join('');
  }

  function render() {
    const c = cart || { items: [], item_count: 0, items_subtotal_price: 0, total_price: 0, original_total_price: 0 };
    badges(c.item_count);
    countEl.textContent = c.item_count ? '(' + c.item_count + ')' : '';
    const empty = !c.items.length;
    emptyEl.hidden = !empty;
    linesEl.hidden = empty;
    foot.hidden = empty;
    root.classList.toggle('is-empty', empty);

    // keep the keyboard where it was when the lines are drawn again
    const af = doc.activeElement;
    const fLine = af && af.closest && af.closest('.sjc-line');
    const fKey = fLine && fLine.getAttribute('data-key');
    const fAct = af && af.getAttribute && af.getAttribute('data-act');
    linesEl.innerHTML = c.items.map(lineHTML).join('');
    const want = c.items.filter((i) => i.product_has_only_default_variant === false && !(i.handle in products)).map((i) => i.handle);
    if (want.length) Promise.all(want.map(productOf)).then(() => { if (cart === c) render(); });
    if (fKey && fAct) {
      const back = [].find.call(linesEl.querySelectorAll('.sjc-line'), (l) => l.getAttribute('data-key') === fKey);
      const btn = back && back.querySelector('[data-act="' + fAct + '"]');
      if (btn) btn.focus({ preventScroll: true });
      else if (isOpen) q('.sjc__close').focus({ preventScroll: true });
    }
    renderTiers(c);
    if (!empty) renderSums(c);
    if (noteEl && doc.activeElement !== noteEl && typeof c.note === 'string') noteEl.value = c.note;
  }

  function goCheckout(btn) {
    if (btn) btn.classList.add('is-busy');
    flush().then(() => { location.href = checkoutUrl(); });
  }

  function flash(keys) {
    (keys || []).forEach((k) => {
      const l = [].find.call(linesEl.querySelectorAll('.sjc-line'), (x) => x.getAttribute('data-key') === k);
      if (!l) return;
      l.classList.add('is-new');
      setTimeout(() => l.classList.remove('is-new'), 1800);
    });
    const first = keys && keys.length && lineEl(keys[0]);
    // on tall screens the lines scroll on their own, elsewhere the whole body
    const sc = linesEl.scrollHeight > linesEl.clientHeight + 1 ? linesEl : body;
    const top = first ? sc.scrollTop + first.getBoundingClientRect().top - sc.getBoundingClientRect().top - 12 : 0;
    sc.scrollTo({ top: Math.max(0, top), behavior: reduced ? 'auto' : 'smooth' });
  }

  /* ---- quantities ------------------------------------------------------- */
  const timers = {};
  function lineEl(key) {
    return [].find.call(linesEl.querySelectorAll('.sjc-line'), (l) => l.getAttribute('data-key') === key);
  }
  function setQty(key, n) {
    const it = cart && cart.items.find((i) => i.key === key);
    if (!it) return;
    n = Math.max(0, n);
    const l = lineEl(key);
    if (l) {
      const out = l.querySelector('.sjc-qty__n');
      if (out) out.textContent = n;
      l.classList.add('is-busy');
      if (n === 0) l.classList.add('is-leaving');
      const err = l.querySelector('[data-err]');
      if (err) err.hidden = true;
    }
    if (timers[key]) clearTimeout(timers[key].t);
    const run = () => {
      delete timers[key];
      return queue(() => post(R.change + '.js', { id: key, quantity: n }))
        .then((c) => {
          const now = c.items.find((i) => i.key === key);
          took(c);
          if (now && now.quantity < n) lineError(key, 'Only ' + now.quantity + ' of this piece can be ordered.');
        })
        .catch((err) => {
          refresh().then(() => lineError(key, err.message)).catch(() => {});
        });
    };
    timers[key] = { run, t: setTimeout(run, n === 0 ? 0 : 320) };
  }
  // sends whatever is still waiting, and resolves once the cart has it
  function flush() {
    Object.keys(timers).forEach((k) => { clearTimeout(timers[k].t); timers[k].run(); });
    if (noteRun) noteRun();
    return chain;
  }
  function lineError(key, text) {
    const l = lineEl(key);
    const err = l && l.querySelector('[data-err]');
    if (err) { err.textContent = text; err.hidden = false; }
    else notice(text, 'error');
  }
  linesEl.addEventListener('click', (e) => {
    const b = e.target.closest('[data-act]');
    if (!b) return;
    const l = b.closest('.sjc-line');
    const key = l.getAttribute('data-key');
    const shown = parseInt(l.querySelector('.sjc-qty__n').textContent, 10) || 0;
    const act = b.getAttribute('data-act');
    if (act === 'inc') setQty(key, shown + 1);
    else if (act === 'dec') setQty(key, shown - 1);
    else if (act === 'remove') setQty(key, 0);
  });

  /* ---- the gift note ---------------------------------------------------- */
  let noteRun = null;
  if (noteEl) {
    let nt = 0;
    noteEl.addEventListener('input', () => {
      clearTimeout(nt);
      noteRun = () => { noteRun = null; clearTimeout(nt); queue(() => post(R.update + '.js', { note: noteEl.value })).catch(() => {}); };
      nt = setTimeout(noteRun, 600);
    });
    const box = q('[data-sjc-note-box]');
    if (box && noteEl.value.trim()) box.open = true;
  }

  const checkoutForm = q('.sjc__checkout-form');
  if (checkoutForm) checkoutForm.addEventListener('submit', (e) => {
    e.preventDefault();
    const btn = q('[data-sjc-checkout]');
    if (btn.classList.contains('is-busy')) return;
    goCheckout(btn);
  });
  // back from checkout: nothing should still look busy
  window.addEventListener('pageshow', () => { const b = q('[data-sjc-checkout]'); if (b) b.classList.remove('is-busy'); });

  /* ---- recommendations -------------------------------------------------- */
  const norm = (p) => {
    const vs = p.variants || [];
    const v = vs.find((x) => x.available) || vs[0];
    return {
      id: p.id,
      handle: p.handle,
      title: p.title,
      url: p.url || slash(R.root) + 'products/' + p.handle,
      price: p.price,
      compare: p.compare_at_price || 0,
      available: p.available,
      variant: v ? v.id : 0,
      multi: vs.length > 1,
      img: p.featured_image ? (typeof p.featured_image === 'string' ? p.featured_image : p.featured_image.src) : (p.media && p.media[0] && (p.media[0].src || (p.media[0].preview_image && p.media[0].preview_image.src))) || null
    };
  };
  const recCache = {};
  let recSeed = null;
  let recToken = 0;
  function loadRecs() {
    if (!D.recsOn) { recsEl.hidden = true; return; }
    const items = cart ? cart.items : [];
    const inBag = new Set(items.map((i) => i.product_id));
    const seed = items.length ? items[0].product_id : null;
    const token = ++recToken;
    const fromShopify = seed
      ? (recCache[seed] ? Promise.resolve(recCache[seed])
        : fetch(R.recs + '.json?product_id=' + seed + '&limit=10&intent=related', { headers: { Accept: 'application/json' } })
          .then((r) => (r.ok ? r.json() : { products: [] }))
          .then((j) => (recCache[seed] = (j.products || []).map(norm)))
          .catch(() => []))
      : Promise.resolve([]);
    fromShopify.then((list) => {
      if (token !== recToken) return;
      const seen = new Set();
      const pool = list.concat(D.fallback || []).filter((p) => {
        if (!p || !p.available || !p.variant || inBag.has(p.id) || seen.has(p.id)) return false;
        seen.add(p.id);
        return true;
      }).slice(0, 8);
      if (!pool.length) { recsEl.hidden = true; rail.innerHTML = ''; return; }
      const sameSeed = seed === recSeed && rail.children.length;
      recSeed = seed;
      rail.innerHTML = pool.map((p) => {
        const off = p.compare > p.price ? Math.round((1 - p.price / p.compare) * 100) : 0;
        return `<li class="sjc-rec">
        <a class="sjc-rec__media" href="${esc(p.url)}" tabindex="-1" aria-hidden="true">${p.img ? `<img src="${esc(pic(p.img, 200))}" alt="" loading="lazy" width="64" height="80">` : ''}</a>
        <div class="sjc-rec__info">
          <a class="sjc-rec__name" href="${esc(p.url)}">${esc(p.title)}</a>
          <p class="sjc-rec__price">${off ? `<s>${esc(money(p.compare))}</s> ` : ''}<b>${esc(money(p.price))}</b>${off ? ` <em>${off}% off</em>` : ''}</p>
        </div>
        <button type="button" class="sjc-rec__add" data-variant="${p.variant}" data-handle="${esc(p.handle)}"${p.multi ? ' data-multi' : ''} aria-label="${p.multi ? 'Choose a size of' : 'Add'} ${esc(p.title)}">${icon('plus')}</button>
      </li>`;
      }).join('');
      recsEl.hidden = false;
      if (!sameSeed) rail.scrollLeft = 0;
      railArrows();
    });
  }

  function railArrows() {
    const max = rail.scrollWidth - rail.clientWidth - 2;
    const prev = q('[data-sjc-rail="-1"]');
    const next = q('[data-sjc-rail="1"]');
    if (prev) prev.disabled = rail.scrollLeft <= 2;
    if (next) next.disabled = rail.scrollLeft >= max;
    q('.sjc__arrows').hidden = max <= 0;
  }
  rail.addEventListener('scroll', () => requestAnimationFrame(railArrows), { passive: true });
  window.addEventListener('resize', () => { if (isOpen) railArrows(); });
  recsEl.addEventListener('click', (e) => {
    const a = e.target.closest('[data-sjc-rail]');
    if (a) {
      const card = rail.querySelector('.sjc-rec');
      const step = card ? card.getBoundingClientRect().width + 12 : 200;
      rail.scrollBy({ left: step * Number(a.getAttribute('data-sjc-rail')), behavior: reduced ? 'auto' : 'smooth' });
      return;
    }
    const b = e.target.closest('.sjc-rec__add');
    if (b) quick(b);
  });

  /* ---- sizes and colours, changed in the bag --------------------------- *
     Add to bag never stops to ask (the user, 2026-10-29: one click, the
     bag opens). A piece with sizes or colours gets a dropdown per option on
     its line; a change swaps the line for that size, same quantity. A value
     with nothing left to buy is marked sold out and cannot be picked. */
  const optName = (o, i) => (typeof o === 'string' ? o : (o && o.name) || 'Option ' + (i + 1));
  const vOpts = (v) => v.options || [v.option1, v.option2, v.option3].filter((x) => x != null);
  const match = (p, sel) => p.variants.find((v) => vOpts(v).every((x, i) => x === sel[i]));
  const products = {}; // handle -> product (false when it could not be read)
  function productOf(handle) {
    return fetch(slash(R.root) + 'products/' + encodeURIComponent(handle) + '.js', { headers: { Accept: 'application/json' } })
      .then((r) => (r.ok ? r.json() : false))
      .catch(() => false)
      .then((p) => { products[handle] = p; return p; });
  }
  function picksHTML(it) {
    const p = products[it.handle];
    if (!p || !p.variants || p.variants.length < 2) return '';
    const v = p.variants.find((x) => x.id === (it.variant_id || it.id));
    if (!v) return '';
    const cur = vOpts(v);
    return p.options.map((o, i) => {
      const values = [];
      p.variants.forEach((x) => { const val = vOpts(x)[i]; if (values.indexOf(val) < 0) values.push(val); });
      if (values.length < 2) return `<p class="sjc-line__opt">${esc(optName(o, i))}: ${esc(cur[i])}</p>`;
      const options = values.map((val) => {
        const left = p.variants.some((x) => x.available && vOpts(x)[i] === val);
        const on = cur[i] === val;
        return `<option value="${esc(val)}"${on ? ' selected' : ''}${!left && !on ? ' disabled' : ''}>${esc(val)}${left ? '' : ' (sold out)'}</option>`;
      }).join('');
      return `<label class="sjc-line__pick"><span>${esc(optName(o, i))}</span><select data-opt="${i}" aria-label="${esc(optName(o, i))} of ${esc(it.product_title)}">${options}</select></label>`;
    }).join('');
  }
  linesEl.addEventListener('change', (e) => {
    const sel = e.target.closest && e.target.closest('select[data-opt]');
    if (!sel) return;
    const l = sel.closest('.sjc-line');
    const key = l.getAttribute('data-key');
    const it = cart && cart.items.find((x) => x.key === key);
    const p = it && products[it.handle];
    if (!p) return;
    const i = Number(sel.getAttribute('data-opt'));
    const cur = vOpts(p.variants.find((x) => x.id === (it.variant_id || it.id)) || p.variants[0]);
    const want = cur.map((val, k) => { const s2 = l.querySelector('select[data-opt="' + k + '"]'); return s2 ? s2.value : val; });
    let v = match(p, want);
    // that mix is gone: keep the new choice, move the others to what is left
    if (!v || !v.available) v = p.variants.find((x) => x.available && vOpts(x)[i] === sel.value);
    if (!v || v.id === (it.variant_id || it.id)) { render(); return; }
    l.classList.add('is-busy');
    // the new size first, so a failure leaves the bag as it was
    queue(() => post(R.add + '.js', { items: [{ id: v.id, quantity: it.quantity }] })
      .then(() => post(R.change + '.js', { id: key, quantity: 0 })))
      .then((c) => took(c))
      .catch((err) => { refresh().then(() => notice(err.message, 'error')).catch(() => {}); });
  });

  /* ---- adding from anywhere --------------------------------------------- */
  function busy(el, on) {
    if (!el) return;
    el.classList.toggle('is-busy', on);
    if (el.tagName === 'BUTTON') {
      if (on) { el.dataset.sjcWas = el.disabled ? '1' : ''; el.disabled = true; }
      else el.disabled = el.dataset.sjcWas === '1';
    }
    el.setAttribute('aria-busy', on ? 'true' : 'false');
  }

  function quick(el) {
    const id = parseInt(el.getAttribute('data-variant'), 10);
    if (!id || el.classList.contains('is-busy')) return;
    const label = el.classList.contains('piece__quick') ? el.textContent : null;
    if (label) el.textContent = 'Adding';
    busy(el, true);
    add([{ id, quantity: 1 }])
      .then((keys) => {
        busy(el, false);
        if (label) el.textContent = label;
        open(true);
        added();
        flash(keys);
      })
      .catch((err) => {
        busy(el, false);
        if (label) el.textContent = label;
        open(true);
        notice(err.message, 'error');
      });
  }

  const isCartLink = (a) => {
    if (a.hasAttribute('data-sj-bag')) return true;
    if (a.target && a.target !== '_self') return false;
    try {
      const u = new URL(a.href, location.href);
      return u.origin === location.origin && u.pathname.replace(/\/$/, '') === cartPath && !u.search;
    } catch (e) { return false; }
  };

  doc.addEventListener('click', (e) => {
    if (e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey || e.altKey) return;
    const t = e.target.closest ? e.target : e.target.parentNode;
    if (!t || !t.closest) return;
    const label = t.closest('.piece__quick[data-variant]');
    if (label) {
      e.preventDefault();
      quick(label);
      return;
    }

    const a = t.closest('a[href]');
    if (a && !root.contains(a) && isCartLink(a)) {
      e.preventDefault();
      open();
    }
  });

  doc.addEventListener('submit', (e) => {
    const f = e.target;
    if (e.defaultPrevented || !f || f.tagName !== 'FORM' || root.contains(f)) return;
    let path = '';
    try { path = new URL(f.getAttribute('action') || '', location.href).pathname; } catch (err) { return; }
    if (!/\/cart\/add(\.js)?$/.test(path)) return;
    e.preventDefault();
    const btn = e.submitter || f.querySelector('[type="submit"]');
    const fd = new FormData(f);
    fd.delete('return_to');
    busy(btn, true);
    addForm(fd)
      .then((keys) => { busy(btn, false); open(true); added(); flash(keys); })
      .catch((err) => {
        if (err.status) { open(true); notice(err.message, 'error'); }
        else f.submit(); // the network, not the cart: let the form go the old way
      })
      .then(() => busy(btn, false));
  });

  /* ---- start ------------------------------------------------------------ */
  window.SJCart = {
    open,
    close,
    refresh,
    add: (id, qty) => add([{ id: Number(id), quantity: qty || 1 }]).then((keys) => { open(true); added(); flash(keys); return keys; })
  };

  // the page came back from the back/forward cache: the bag may have changed
  window.addEventListener('pageshow', (e) => { if (e.persisted) refresh().catch(() => {}); });

  if (location.hash === '#cart') {
    history.replaceState(null, '', location.pathname + location.search);
    open();
  } else if (cart) {
    badges(cart.item_count);
  }
  // the page's own copy of the bag can be older than the bag itself (another
  // tab, the back button), so it is read once more when the page is idle
  const wake = () => { if (!isOpen) refresh().catch(() => {}); };
  if ('requestIdleCallback' in window) requestIdleCallback(wake, { timeout: 2500 });
  else setTimeout(wake, 1200);
})();
